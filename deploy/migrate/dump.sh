#!/bin/sh
#
# Dump the SmartSeller data out of a Supabase Postgres (the cloud project).
# Needs only Docker: pg_dump/psql run from the official postgres image, whose
# client must be at least as new as the server (Supabase cloud runs 15 or 17).
#
#   SOURCE_DB_URL='postgresql://postgres.<ref>:<password>@<pooler-host>:5432/postgres' \
#     sh deploy/migrate/dump.sh [output-dir]
#
# Use the "Session pooler" connection string from the Supabase dashboard
# (Connect -> Session pooler): it works over IPv4, unlike the direct host.
# The URL is read from the environment, never from the command line, so the
# password does not end up in shell history or `ps`. It may also be put in
# deploy/migrate/.env (gitignored) as SOURCE_DB_URL=...
#
# Output (all plain SQL / CSV, nothing is changed on the source):
#   schema.sql         public schema: tables, functions, policies, grants
#   auth-users.csv     auth.users       (password hashes included)
#   auth-identities.csv auth.identities
#   data-public.sql    every row of every public table
#   fixups.sql         triggers on auth.* tables + Realtime publication
#   counts.tsv         exact row counts, compared by restore.sh
#   info.txt           server version, extensions, anything that needs a look

set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
if [ -z "${SOURCE_DB_URL:-}" ] && [ -f "$HERE/.env" ]; then
    # shellcheck disable=SC1091
    . "$HERE/.env"
fi
[ -n "${SOURCE_DB_URL:-}" ] || { echo "ERROR: set SOURCE_DB_URL (see the header of $0)" >&2; exit 1; }
export SOURCE_DB_URL

OUT=${1:-"$HERE/dump-$(date +%Y%m%d-%H%M%S)"}
mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)
PG_IMAGE=${PG_IMAGE:-postgres:17-alpine}

# Run a postgres client tool in a throwaway container with the URL in its
# environment. MSYS_NO_PATHCONV keeps Git Bash on Windows from rewriting
# the /out path.
pg() {
    MSYS_NO_PATHCONV=1 docker run --rm -i \
        -e SOURCE_DB_URL -e SCHEMA_ARGS -e PGCONNECT_TIMEOUT=20 -e PGOPTIONS='-c statement_timeout=0' \
        -v "$OUT:/out" "$PG_IMAGE" "$@"
}
q() { pg sh -c 'psql "$SOURCE_DB_URL" -X -v ON_ERROR_STOP=1 -Atq "$@"' sh "$@"; }

echo "===> Connecting"
version=$(q -c "select current_setting('server_version')")
echo "     source Postgres $version"

# public plus every schema someone created by hand (e.g. erp, analytics).
# Supabase-managed schemas exist on the new instance already.
MANAGED="'auth','storage','realtime','_realtime','extensions','graphql','graphql_public','vault','pgsodium','pgsodium_masks','net','supabase_functions','supabase_migrations','cron','pgbouncer','_analytics','information_schema','pgmq','pgtle','tiger','topology'"
SCHEMAS=$(q -c "select string_agg(nspname, ' ' order by nspname) from pg_namespace
  where nspname = 'public' or (nspname not like 'pg\_%' and nspname not in ($MANAGED))")
SCHEMA_LIST="'$(echo "$SCHEMAS" | sed "s/ /','/g")'"
SCHEMA_ARGS=""
for s in $SCHEMAS; do SCHEMA_ARGS="$SCHEMA_ARGS --schema=$s"; done
export SCHEMA_ARGS
echo "     schemas: $SCHEMAS"

echo "===> schema.sql ($SCHEMAS)"
pg sh -c 'pg_dump "$SOURCE_DB_URL" --schema-only $SCHEMA_ARGS \
    --no-publications --no-subscriptions --quote-all-identifiers \
    --file=/out/schema.sql'

echo "===> auth-users.csv, auth-identities.csv"
q -c "\\copy (select * from auth.users order by created_at, id) to '/out/auth-users.csv' with (format csv, header true)"
q -c "\\copy (select * from auth.identities order by created_at, id) to '/out/auth-identities.csv' with (format csv, header true)"

echo "===> data-public.sql (all rows of $SCHEMAS)"
pg sh -c 'pg_dump "$SOURCE_DB_URL" --data-only $SCHEMA_ARGS \
    --no-publications --no-subscriptions --quote-all-identifiers \
    --file=/out/data-public.sql'

echo "===> fixups.sql"
{
    echo "-- Generated by deploy/migrate/dump.sh from the source database."
    echo "-- Triggers that public functions hang on auth tables (not part of a"
    echo "-- public-schema dump), and the tables Realtime publishes."
    echo
    q -c "set search_path = ''" -c "
      select format('drop trigger if exists %I on %I.%I;', t.tgname, n.nspname, c.relname)
             || chr(10) || pg_get_triggerdef(t.oid) || ';'
      from pg_trigger t
      join pg_class c on c.oid = t.tgrelid
      join pg_namespace n on n.oid = c.relnamespace
      join pg_proc p on p.oid = t.tgfoid
      join pg_namespace pn on pn.oid = p.pronamespace
      where n.nspname = 'auth' and not t.tgisinternal and pn.nspname in ($SCHEMA_LIST)
      order by c.relname, t.tgname"
    echo
    q -c "
      select format(\$f\$do \$x\$ begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables
                     where pubname = 'supabase_realtime' and schemaname = %L and tablename = %L) then
    alter publication supabase_realtime add table %I.%I;
  end if;
end \$x\$;\$f\$, schemaname, tablename, schemaname, tablename)
      from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname in ($SCHEMA_LIST)
      order by tablename"
} > "$OUT/fixups.sql"

echo "===> counts.tsv"
q -F "$(printf '\t')" -c "
  select n.nspname || '.' || c.relname,
         (xpath('/row/c/text()', query_to_xml(format('select count(*) as c from %I.%I', n.nspname, c.relname), false, true, '')))[1]::text
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where c.relkind in ('r', 'p')
    and (n.nspname in ($SCHEMA_LIST) or (n.nspname = 'auth' and c.relname in ('users', 'identities')))
  order by 1" > "$OUT/counts.tsv"

echo "===> info.txt"
{
    echo "dumped_at: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "source_version: $version"
    echo
    echo "# extensions (name version schema)"
    q -F ' ' -c "select e.extname, e.extversion, n.nspname from pg_extension e join pg_namespace n on n.oid = e.extnamespace order by 1"
    echo
    echo "# tables outside public/auth that hold rows and are NOT migrated (review)"
    q -F ' ' -c "
      select n.nspname || '.' || c.relname, c.reltuples::bigint
      from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where c.relkind = 'r' and c.reltuples > 0
        and n.nspname not in ($SCHEMA_LIST) and n.nspname not in ('auth', 'pg_catalog', 'information_schema', 'extensions',
                              'realtime', '_realtime', 'storage', 'supabase_functions', 'supabase_migrations',
                              'net', 'pgsodium', 'vault', 'graphql', 'graphql_public', 'cron', 'pgbouncer', '_analytics')
      order by 1"
    echo
    echo "# storage objects (files) — not migrated by this script"
    q -c "select count(*) from storage.objects" 2>/dev/null || echo "n/a"
    echo
    echo "# custom roles (not created by Supabase) — not migrated"
    q -c "
      select rolname from pg_roles
      where rolname !~ '^(pg_|supabase|postgres$|anon$|authenticated$|service_role$|authenticator$|dashboard_user$|pgbouncer$|pgsodium|cli_login|tealbase)'
      order by 1"
} > "$OUT/info.txt"

chmod 600 "$OUT"/* 2>/dev/null || true

echo
echo "Dump written to $OUT"
echo "Rows per table:"
sed 's/^/    /' "$OUT/counts.tsv"
echo
echo "Review $OUT/info.txt, then copy the folder to the server and run restore.sh."
echo "The CSV files hold password hashes: keep the folder private, delete it after the move."
